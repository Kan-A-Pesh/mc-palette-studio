#!/usr/bin/env node
// find-unused.mjs — Detect unused source files in the Somnium monorepo
//
// Walks the import graph from configured entry points (.doctor/config/entry-points)
// plus Next.js convention files (page.tsx, layout.tsx, route.ts, ...) and package
// barrels (packages/*/src/index.ts, packages/database/schema/index.ts).
//
// Path resolution rules:
//   @/foo            → apps/web/foo                  (Next.js alias)
//   @repo/database   → packages/database/index.ts    (package.json exports `.`)
//   @repo/server     → packages/server/src/routers/app.ts (per package exports)
//   @repo/ui/<sub>   → packages/ui/src/ui/<sub>{.tsx,.ts,/index.{ts,tsx}}
//                      (source equivalent of dist/ui/*.js export)
//   @repo/ui/hooks/X → packages/ui/src/hooks/X
//   @repo/ui/utils/X → packages/ui/src/utils/X
//   @repo/<pkg>/<x>  → packages/<pkg>/<x>  (best-effort source fallback)
//   ./relative       → resolved relative to source file directory
//   bare imports     → ignored (npm packages, not source files)
//
// Try extensions in order: '', .ts, .tsx, .js, .mjs, /index.ts, /index.tsx, /index.js
//
// Exclusions (never flagged):
//   - *.d.ts
//   - node_modules/, .next/, dist/, build/, .cache/, .turbo/
//   - packages/database/migrations/  (generated by drizzle-kit)
//   - packages/database/schema/auth/auth.ts  (generated by better-auth CLI)
//   - *.test.{ts,tsx}, *.spec.{ts,tsx}
//   - *.stories.tsx  (Storybook)
//
// Usage: node find-unused.mjs [root]
// Output: `UNUSED: <path>` per file, then `TOTAL: N unused file(s)` or `OK: ...`.
// Exit:   1 if any unused, 0 otherwise.

import { readFileSync, existsSync, statSync, readdirSync } from 'fs';
import { join, dirname, relative, resolve, sep, posix } from 'path';
import { execSync } from 'child_process';

const ROOT = resolve(process.argv[2] || '.');
const DOCTOR_DIR = resolve(new URL('.', import.meta.url).pathname, '..', '..', '..');
const ENTRY_CONFIG = join(DOCTOR_DIR, 'config', 'entry-points');

// ─── File discovery (respects .gitignore via git ls-files) ─────────
const SKIP_DIRS = new Set([
  'node_modules', '.git', '.next', 'dist', 'build', '.cache', '.turbo', '.claude', '.doctor',
]);

function listAllFiles() {
  try {
    const out = execSync(
      'git ls-files --cached --others --exclude-standard',
      { cwd: ROOT, encoding: 'utf-8', stdio: ['pipe', 'pipe', 'pipe'] },
    ).trim();
    if (out) {
      return out.split('\n')
        .filter(f => /\.(ts|tsx)$/.test(f))
        .filter(f => existsSync(join(ROOT, f)));
    }
  } catch { /* not in git → fallback */ }
  const out = [];
  function walk(d) {
    let entries;
    try { entries = readdirSync(d); } catch { return; }
    for (const e of entries) {
      if (SKIP_DIRS.has(e)) continue;
      const p = join(d, e);
      let st;
      try { st = statSync(p); } catch { continue; }
      if (st.isDirectory()) walk(p);
      else if (/\.(ts|tsx)$/.test(e)) out.push(relative(ROOT, p));
    }
  }
  walk(ROOT);
  return out;
}

// ─── Exclusion rules ───────────────────────────────────────────────
function isExcluded(rel) {
  if (rel.endsWith('.d.ts')) return true;
  if (/\.(test|spec)\.(ts|tsx)$/.test(rel)) return true;
  if (rel.endsWith('.stories.tsx')) return true;
  if (rel.startsWith('packages/database/migrations/')) return true;
  if (rel === 'packages/database/schema/auth.ts') return true;
  if (rel === 'packages/database/schema/auth-types.ts') return true; // generated alongside auth.ts
  if (rel.includes('/node_modules/')) return true;
  if (rel.includes('/.next/')) return true;
  if (rel.includes('/dist/')) return true;
  if (rel.includes('/build/')) return true;
  return false;
}

// ─── Glob matching (used for entry-point patterns) ─────────────────
// Convert minimal glob (**, *, ?) to a RegExp.
function globToRegex(glob) {
  let re = '^';
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === '*') {
      if (glob[i + 1] === '*') {
        // ** — match any path segments
        i++;
        // consume optional trailing slash
        if (glob[i + 1] === '/') i++;
        re += '(?:.*/)?';
      } else {
        re += '[^/]*';
      }
    } else if (c === '?') {
      re += '[^/]';
    } else if ('.+^$|()[]{}\\'.includes(c)) {
      re += '\\' + c;
    } else {
      re += c;
    }
  }
  re += '$';
  return new RegExp(re);
}

// ─── Read entry-points config ──────────────────────────────────────
function readEntryGlobs() {
  const globs = [];
  if (!existsSync(ENTRY_CONFIG)) return globs;
  const lines = readFileSync(ENTRY_CONFIG, 'utf-8').split('\n');
  for (const raw of lines) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    globs.push(line);
  }
  return globs;
}

// ─── Hard-coded "always entry" rules ───────────────────────────────
// These are entry points even if not enumerated in config (defensive).
const NEXT_CONVENTIONS = /^apps\/[^/]+\/app\/.*\/(page|layout|error|loading|not-found|template|default)\.tsx$/;
const NEXT_CONVENTIONS_ROOT = /^apps\/[^/]+\/app\/(page|layout|error|loading|not-found|template|default)\.tsx$/;
const NEXT_ROUTE = /^apps\/[^/]+\/app\/.*route\.ts$/;
const PACKAGE_BARREL = /^packages\/[^/]+\/(src\/)?index\.ts$/;
const SCHEMA_BARREL = /^packages\/database\/schema\/(.*\/)?index\.ts$/;
const MIDDLEWARE = /^apps\/[^/]+\/middleware\.ts$/;
const CONFIG_FILE = /\.config\.(ts|js|mjs|cjs)$/;
const NEXT_ENV = /next-env\.d\.ts$/;
const DRIZZLE_MIGRATE = /^packages\/[^/]+\/migrate\.ts$/;
// @repo/ui is a library package: every source file is potentially imported
// externally via @repo/ui/<sub>. Treat all packages/ui/src/** as entry points
// so its internal helpers (hooks, utils) are reachable from the import graph.
const UI_SRC_ALL = /^packages\/ui\/src\/.+\.(ts|tsx)$/;

function isConventionEntry(rel) {
  if (NEXT_CONVENTIONS.test(rel)) return true;
  if (NEXT_CONVENTIONS_ROOT.test(rel)) return true;
  if (NEXT_ROUTE.test(rel)) return true;
  if (PACKAGE_BARREL.test(rel)) return true;
  if (SCHEMA_BARREL.test(rel)) return true;
  if (MIDDLEWARE.test(rel)) return true;
  if (CONFIG_FILE.test(rel)) return true;
  if (NEXT_ENV.test(rel)) return true;
  if (DRIZZLE_MIGRATE.test(rel)) return true;
  if (UI_SRC_ALL.test(rel)) return true;
  return false;
}

// ─── Resolve a package.json "exports" entry path → source file ─────
// The exports field often points to ./dist/... — we map dist → src here.
function distToSrc(p) {
  // ./dist/foo/bar.js → ./src/foo/bar.{ts,tsx}
  return p.replace(/^\.?\/?dist\//, './src/').replace(/\.js$/, '');
}

// ─── Cache package.json exports per package ────────────────────────
const pkgCache = new Map();
function getPkgExports(pkgName) {
  // pkgName e.g. "database", "server", "ui", "email", "env"
  if (pkgCache.has(pkgName)) return pkgCache.get(pkgName);
  const pkgJsonPath = join(ROOT, 'packages', pkgName, 'package.json');
  if (!existsSync(pkgJsonPath)) {
    pkgCache.set(pkgName, null);
    return null;
  }
  try {
    const json = JSON.parse(readFileSync(pkgJsonPath, 'utf-8'));
    pkgCache.set(pkgName, json.exports || null);
    return json.exports || null;
  } catch {
    pkgCache.set(pkgName, null);
    return null;
  }
}

// ─── Path candidate generation ─────────────────────────────────────
const EXTENSIONS = ['', '.ts', '.tsx', '.js', '.mjs', '/index.ts', '/index.tsx', '/index.js'];

function resolveCandidates(absPath) {
  const out = [];
  for (const ext of EXTENSIONS) {
    out.push(absPath + ext);
  }
  return out;
}

function firstExisting(absCandidates) {
  for (const c of absCandidates) {
    if (existsSync(c) && statSync(c).isFile()) return c;
  }
  return null;
}

// ─── Resolve an import specifier from a source file → abs path ─────
function resolveImport(specifier, fromAbsFile) {
  // Strip query/hash if any
  const spec = specifier.split('?')[0].split('#')[0];
  if (!spec) return null;

  // Relative imports
  if (spec.startsWith('./') || spec.startsWith('../')) {
    const abs = resolve(dirname(fromAbsFile), spec);
    return firstExisting(resolveCandidates(abs));
  }

  // Next.js alias: @/foo → apps/web/foo
  if (spec.startsWith('@/')) {
    const abs = join(ROOT, 'apps', 'web', spec.slice(2));
    return firstExisting(resolveCandidates(abs));
  }

  // Workspace packages: @repo/<pkg>[/<sub>]
  if (spec.startsWith('@repo/')) {
    const rest = spec.slice('@repo/'.length);
    const slash = rest.indexOf('/');
    const pkgName = slash < 0 ? rest : rest.slice(0, slash);
    const sub = slash < 0 ? null : rest.slice(slash + 1);
    const pkgDir = join(ROOT, 'packages', pkgName);

    // Try exports field if present
    const exports = getPkgExports(pkgName);
    if (exports && typeof exports === 'object') {
      const key = sub === null ? '.' : `./${sub}`;
      // Direct match
      if (exports[key]) {
        const target = typeof exports[key] === 'string'
          ? exports[key]
          : (exports[key].source || exports[key].default || exports[key].types);
        if (typeof target === 'string') {
          const srcMapped = distToSrc(target);
          const abs = join(pkgDir, srcMapped);
          const found = firstExisting(resolveCandidates(abs));
          if (found) return found;
        }
      }
      // Wildcard match: e.g. "./*" → "./dist/ui/*.js"
      for (const [k, v] of Object.entries(exports)) {
        if (!k.includes('*')) continue;
        const pattern = k === '.' ? '' : k.slice(2); // "./hooks/*" → "hooks/*"
        const star = pattern.indexOf('*');
        if (star < 0) continue;
        const prefix = pattern.slice(0, star);
        const suffix = pattern.slice(star + 1);
        const subKey = sub === null ? '' : sub;
        if (!subKey.startsWith(prefix) || !subKey.endsWith(suffix)) continue;
        const match = subKey.slice(prefix.length, subKey.length - suffix.length);
        const target = typeof v === 'string'
          ? v
          : (v.source || v.default || v.types);
        if (typeof target !== 'string') continue;
        const targetPath = distToSrc(target).replace('*', match);
        const abs = join(pkgDir, targetPath);
        const found = firstExisting(resolveCandidates(abs));
        if (found) return found;
      }
    }

    // Fallback: try common source paths
    const candidates = [];
    if (sub === null) {
      // No subpath: try package barrels
      candidates.push(join(pkgDir, 'src', 'index'));
      candidates.push(join(pkgDir, 'index'));
    } else {
      // Heuristic: @repo/ui/<x> → src/ui/<x> ; otherwise src/<sub> or just <sub>
      if (pkgName === 'ui') {
        candidates.push(join(pkgDir, 'src', 'ui', sub));
      }
      candidates.push(join(pkgDir, 'src', sub));
      candidates.push(join(pkgDir, sub));
    }
    for (const c of candidates) {
      const found = firstExisting(resolveCandidates(c));
      if (found) return found;
    }
    return null;
  }

  // Bare import → ignore (external package)
  return null;
}

// ─── Parse imports from a file ────────────────────────────────────
// Matches: import X from "..."; import "...";  export ... from "..."; await import("...")
const IMPORT_RE = /(?:import|export)\s+(?:[^"';]*?\s+from\s+)?["']([^"']+)["']|import\s*\(\s*["']([^"']+)["']\s*\)|require\s*\(\s*["']([^"']+)["']\s*\)/g;

function extractImports(content) {
  const out = [];
  let m;
  IMPORT_RE.lastIndex = 0;
  while ((m = IMPORT_RE.exec(content)) !== null) {
    const spec = m[1] || m[2] || m[3];
    if (spec) out.push(spec);
  }
  return out;
}

// ─── Main ──────────────────────────────────────────────────────────
function toRel(absPath) {
  return relative(ROOT, absPath).split(sep).join(posix.sep);
}

const allFiles = listAllFiles();
const filtered = allFiles.filter(f => !isExcluded(f));

// Build entry-point set
const entryGlobs = readEntryGlobs();
const entryRegexes = entryGlobs.map(globToRegex);

const entrySet = new Set();
for (const rel of filtered) {
  if (entryRegexes.some(r => r.test(rel))) {
    entrySet.add(rel);
    continue;
  }
  if (isConventionEntry(rel)) {
    entrySet.add(rel);
  }
}

// Treat anything referenced by a package.json `exports` field as an entry
// point: it's a publicly exposed API even if not imported within the monorepo.
function addPackageExportEntries() {
  // Walk packages/*/package.json
  let pkgDirs;
  try { pkgDirs = readdirSync(join(ROOT, 'packages')); }
  catch { return; }
  for (const pkgName of pkgDirs) {
    const pkgDir = join(ROOT, 'packages', pkgName);
    const exports = getPkgExports(pkgName);
    if (!exports || typeof exports !== 'object') continue;
    for (const [, v] of Object.entries(exports)) {
      const target = typeof v === 'string' ? v : (v && (v.source || v.default || v.types));
      if (typeof target !== 'string') continue;
      if (target.includes('*')) continue; // wildcard handled via import-walking
      const mapped = distToSrc(target);
      const abs = join(pkgDir, mapped);
      const found = firstExisting(resolveCandidates(abs));
      if (found) {
        const rel = toRel(found);
        if (!isExcluded(rel)) entrySet.add(rel);
      }
    }
  }
}
addPackageExportEntries();

// BFS from entry points, accumulating reachable files
const reached = new Set();
const queue = [];
for (const ep of entrySet) {
  reached.add(ep);
  queue.push(join(ROOT, ep));
}

while (queue.length > 0) {
  const absFile = queue.shift();
  let content;
  try { content = readFileSync(absFile, 'utf-8'); }
  catch { continue; }
  const imports = extractImports(content);
  for (const spec of imports) {
    const resolved = resolveImport(spec, absFile);
    if (!resolved) continue;
    const rel = toRel(resolved);
    if (reached.has(rel)) continue;
    reached.add(rel);
    queue.push(resolved);
  }
}

// Report unused: in filtered set but not in reached
const unused = filtered.filter(f => !reached.has(f)).sort();

for (const f of unused) {
  console.log(`UNUSED: ${f}`);
}

if (unused.length === 0) {
  console.log('OK: No unused files detected');
  process.exit(0);
} else {
  console.log('');
  console.log(`TOTAL: ${unused.length} unused file(s)`);
  process.exit(1);
}
